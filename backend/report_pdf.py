"""Export PDF générique des résultats (plan de retouche, dossier de spot, diagnostic stratégique, prompt du tuteur, audits).

L'interface convertit le résultat affiché en blocs simples (titres, paragraphes, puces, paires clé/valeur, tableaux) ;
ce module les met en page (A4, pied de page numéroté) sans rien conserver. Latin via Helvetica ; arabe via pdf_gen (reshaper + bidi).
"""
from __future__ import annotations

import io
import re
from datetime import date

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import HRFlowable, KeepTogether, SimpleDocTemplate, Spacer, Table, TableStyle

from . import pdf_gen

MAX_BLOCKS, MAX_TEXT, MAX_COLS, MAX_ROWS = 800, 6000, 6, 250
KINDS = {"h2", "h3", "p", "li", "kv", "table", "pre"}
FOOT = {"fr": "Document généré par CARRIVA le {d} · page {n}", "en": "Document generated by CARRIVA on {d} · page {n}", "de": "Von CARRIVA erstellt am {d} · Seite {n}",
        "es": "Documento generado por CARRIVA el {d} · página {n}", "it": "Documento generato da CARRIVA il {d} · pagina {n}", "ar": "CARRIVA {d} - {n}"}
_SYMBOLS = {"→": "->", "←": "<-", "≈": "~", "≤": "<=", "≥": ">=", "✓": "", "★": "*", "•": "-", "−": "-", " ": " ", " ": " ", "​": "", "‎": "", "‏": "", "’": "'", "‘": "'"}
_CTRL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


class ReportError(ValueError):
    pass


def clean(v) -> str:
    """Texte sûr pour Helvetica (cp1252) + arabe ; supprime les caractères de contrôle et les symboles non rendables."""
    s = _CTRL.sub("", str(v if v is not None else ""))
    for a, b in _SYMBOLS.items():
        s = s.replace(a, b)
    out = []
    for ch in s:
        if pdf_gen.has_arabic(ch):
            out.append(ch)
            continue
        try:
            ch.encode("cp1252")
            out.append(ch)
        except UnicodeEncodeError:
            out.append("")
    return re.sub(r"[ \t]{2,}", " ", "".join(out))[:MAX_TEXT]


def normalise(blocks: list) -> list[dict]:
    if not isinstance(blocks, list) or not blocks:
        raise ReportError("Aucun contenu à exporter.")
    out = []
    for b in blocks[:MAX_BLOCKS]:
        if not isinstance(b, dict) or b.get("t") not in KINDS:
            continue
        k = b["t"]
        if k == "kv":
            kk, vv = clean(b.get("k")).strip(), clean(b.get("v")).strip()
            if kk or vv:
                out.append({"t": "kv", "k": kk, "v": vv})
        elif k == "table":
            head = [clean(x) for x in (b.get("head") or [])][:MAX_COLS]
            rows = [[clean(c) for c in r][:MAX_COLS] for r in (b.get("rows") or []) if isinstance(r, list)][:MAX_ROWS]
            if rows or head:
                n = max([len(head)] + [len(r) for r in rows])
                out.append({"t": "table", "head": head + [""] * (n - len(head)) if head else [], "rows": [r + [""] * (n - len(r)) for r in rows]})
        else:
            txt = clean(b.get("text")).strip()
            if txt:
                out.append({"t": k, "text": txt})
    if not out:
        raise ReportError("Aucun contenu à exporter.")
    return out


def needs_arabic(blocks: list[dict]) -> bool:
    for b in blocks:
        vals = [b.get("text", ""), b.get("k", ""), b.get("v", "")] + list(b.get("head", [])) + [c for r in b.get("rows", []) for c in r]
        if any(pdf_gen.has_arabic(v) for v in vals if v):
            return True
    return False


def render(title: str, blocks: list, lang: str = "fr", subtitle: str = "") -> bytes:
    blocks = normalise(blocks)
    lang = lang if lang in FOOT else "fr"
    title, subtitle = clean(title).strip() or "CARRIVA", clean(subtitle).strip()
    if needs_arabic(blocks + [{"t": "p", "text": title}]) and not pdf_gen._ar_ok:
        raise ReportError("Police arabe absente : lancez `python backend/fonts/fetch_fonts.py` pour exporter en arabe.")
    rtl = lang == "ar"
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm, topMargin=1.8 * cm, bottomMargin=1.8 * cm, title=title[:120], author="CARRIVA")
    W = doc.width
    ss = getSampleStyleSheet()
    base = ParagraphStyle("rb", parent=ss["BodyText"], fontSize=10, leading=14, textColor=colors.HexColor("#111827"))
    h1 = ParagraphStyle("rh1", parent=base, fontName="Helvetica-Bold", fontSize=18, leading=22, textColor=pdf_gen.DEEP, spaceAfter=2)
    h2 = ParagraphStyle("rh2", parent=base, fontName="Helvetica-Bold", fontSize=13, leading=17, textColor=pdf_gen.EU_BLUE, spaceBefore=12, spaceAfter=3)
    h3 = ParagraphStyle("rh3", parent=base, fontName="Helvetica-Bold", fontSize=11, leading=15, textColor=pdf_gen.DEEP, spaceBefore=8, spaceAfter=2)
    li = ParagraphStyle("rli", parent=base, leftIndent=0 if rtl else 12, rightIndent=12 if rtl else 0, bulletIndent=0)
    sub = ParagraphStyle("rsub", parent=base, textColor=pdf_gen.GRAY, fontSize=9)
    pre = ParagraphStyle("rpre", parent=base, fontName="Courier", fontSize=8.5, leading=11.5)
    cell = ParagraphStyle("rcell", parent=base, fontSize=8.5, leading=11)
    cellb = ParagraphStyle("rcellb", parent=cell, fontName="Helvetica-Bold", textColor=colors.white)

    def P(text, st, width=W):
        return pdf_gen.para(text, st, width, lang)

    flow = [P(title, h1), HRFlowable(width="100%", color=pdf_gen.EU_LINE, thickness=0.8, spaceBefore=2, spaceAfter=6)]
    if subtitle:
        flow.append(P(subtitle, sub))
    kv_buf: list[dict] = []

    def flush_kv():
        if not kv_buf:
            return
        cols = 3
        rows = []
        for i in range(0, len(kv_buf), cols):
            chunk = kv_buf[i:i + cols]
            rows.append([[P(x["k"], sub, W / cols - 10), P(x["v"], ParagraphStyle("kvv", parent=base, fontName="Helvetica-Bold"), W / cols - 10)] for x in chunk] + [""] * (cols - len(chunk)))
        t = Table(rows, colWidths=[W / cols] * cols)
        t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("BOX", (0, 0), (-1, -1), 0.4, pdf_gen.EU_LINE), ("INNERGRID", (0, 0), (-1, -1), 0.4, pdf_gen.EU_LINE), ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4)]))
        flow.append(t); flow.append(Spacer(1, 4)); kv_buf.clear()

    for b in blocks:
        if b["t"] != "kv":
            flush_kv()
        k = b["t"]
        if k == "h2":
            flow.append(KeepTogether([P(b["text"], h2)]))
        elif k == "h3":
            flow.append(KeepTogether([P(b["text"], h3)]))
        elif k == "p":
            flow.append(P(b["text"], base)); flow.append(Spacer(1, 3))
        elif k == "li":
            flow.append(P(("- " if not rtl else "") + b["text"] + (" -" if rtl else ""), li))
        elif k == "pre":
            for line in b["text"].split("\n"):
                flow.append(P(line if line.strip() else " ", pre, W))
            flow.append(Spacer(1, 4))
        elif k == "kv":
            kv_buf.append(b)
        elif k == "table":
            n = len(b["rows"][0]) if b["rows"] else len(b["head"])
            data = ([[P(c, cellb, W / n - 8) for c in b["head"]]] if b["head"] else []) + [[P(c, cell, W / n - 8) for c in r] for r in b["rows"]]
            if rtl:
                data = [list(reversed(r)) for r in data]
            t = Table(data, colWidths=[W / n] * n, repeatRows=1 if b["head"] else 0)
            style = [("VALIGN", (0, 0), (-1, -1), "TOP"), ("GRID", (0, 0), (-1, -1), 0.4, pdf_gen.EU_LINE), ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                     ("ROWBACKGROUNDS", (0, 1 if b["head"] else 0), (-1, -1), [colors.white, colors.HexColor("#F3F6FC")])]
            if b["head"]:
                style.append(("BACKGROUND", (0, 0), (-1, 0), pdf_gen.EU_BLUE))
            t.setStyle(TableStyle(style))
            flow.append(t); flow.append(Spacer(1, 6))
    flush_kv()
    today = date.today().strftime("%d/%m/%Y")

    def footer(c, d):
        c.saveState(); c.setFont("Helvetica", 8); c.setFillColor(pdf_gen.GRAY)
        c.drawCentredString(A4[0] / 2, 1.0 * cm, FOOT[lang].format(d=today, n=d.page)); c.restoreState()

    doc.build(flow, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()
